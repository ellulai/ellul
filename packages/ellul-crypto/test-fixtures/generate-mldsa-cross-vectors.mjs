/**
 * Generate ML-DSA cross-implementation test vectors.
 *
 * Signs test messages with @noble/post-quantum (TypeScript/JS implementation)
 * and outputs fixtures that the Rust pqcrypto-dilithium tests can verify.
 * This ensures that signatures created by one implementation can be verified
 * by the other — critical because VPS signs (Rust) and API verifies (TS), and
 * browser signs intents (TS) and VPS verifies (TS @noble).
 *
 * Run once: node generate-mldsa-cross-vectors.mjs
 * Output:   mldsa-cross-vectors.json (committed alongside this script)
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Dynamic import for ESM-only noble package
// Resolve from apps/api where @noble/post-quantum is installed
import { createRequire } from "node:module";
const require = createRequire(path.resolve(__dirname, "../../../apps/api/package.json"));
const { ml_dsa65, ml_dsa44 } = require("@noble/post-quantum/ml-dsa.js");

function toBase64(buf) {
  return Buffer.from(buf).toString("base64");
}

function generateVector(impl, label, message) {
  const { publicKey, secretKey } = impl.keygen();
  const msgBytes = new TextEncoder().encode(message);
  // noble API: sign(message, secretKey), verify(signature, message, publicKey)
  const signature = impl.sign(msgBytes, secretKey);

  // Verify locally (sanity check)
  const valid = impl.verify(signature, msgBytes, publicKey);
  if (!valid) {
    throw new Error(`Self-verify failed for ${label}`);
  }

  return {
    label,
    message,
    public_key_b64: toBase64(publicKey),
    secret_key_b64: toBase64(secretKey),
    signature_b64: toBase64(signature),
    public_key_size: publicKey.length,
    secret_key_size: secretKey.length,
    signature_size: signature.length,
  };
}

// ML-DSA-65 vectors (used for migration manifest signing)
const mldsa65_vectors = [
  generateVector(ml_dsa65, "mldsa65-simple", "hello post-quantum world"),
  generateVector(ml_dsa65, "mldsa65-manifest-like", JSON.stringify({
    version: 1,
    serverId: "test-server-001",
    snapshotVersion: 42,
    timestamp: "2026-03-31T12:00:00Z",
    chunkCount: 10,
    merkleRootHash: "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789",
  })),
  generateVector(ml_dsa65, "mldsa65-empty", ""),
  generateVector(ml_dsa65, "mldsa65-binary-like", "\x00\x01\x02\xff\xfe\xfd"),
];

// ML-DSA-44 vectors (used for heartbeat signatures and intent signatures)
const mldsa44_vectors = [
  generateVector(ml_dsa44, "mldsa44-heartbeat-like", "1711900800:server-abc-123"),
  generateVector(ml_dsa44, "mldsa44-intent-like", "exec|project:myapp|sha256hash|sess123|keyid456|server-001|nonce789|1711900800000"),
];

const fixture = {
  description: "ML-DSA cross-implementation test vectors (generated by @noble/post-quantum, verified by pqcrypto-dilithium)",
  generator: "@noble/post-quantum",
  verifier: "pqcrypto-dilithium (Rust)",
  vectors: {
    mldsa65: mldsa65_vectors,
    mldsa44: mldsa44_vectors,
  },
};

const outPath = path.join(__dirname, "mldsa-cross-vectors.json");
fs.writeFileSync(outPath, JSON.stringify(fixture, null, 2) + "\n");
console.log(`Wrote ${outPath} with ${mldsa65_vectors.length} ML-DSA-65 and ${mldsa44_vectors.length} ML-DSA-44 vectors`);

// Also verify that key sizes match expected FIPS 204 values
console.log(`ML-DSA-65: pk=${mldsa65_vectors[0].public_key_size} sk=${mldsa65_vectors[0].secret_key_size} sig=${mldsa65_vectors[0].signature_size}`);
console.log(`ML-DSA-44: pk=${mldsa44_vectors[0].public_key_size} sk=${mldsa44_vectors[0].secret_key_size} sig=${mldsa44_vectors[0].signature_size}`);
