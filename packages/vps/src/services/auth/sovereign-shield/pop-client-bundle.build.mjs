/**
 * Build-time PoP Client Bundle Generator
 *
 * Compiles TypeScript client modules into minified, integrity-verified browser bundles.
 *
 * Pipeline:
 *   1. tsc --noEmit  — full type check (DOM + WebWorker libs, strict mode)
 *   2. esbuild       — bundle + minify + source maps
 *   3. SRI + ETag    — SHA-384 integrity digests, content-hash ETags
 *   4. Manifest      — pop-client-manifest.ts with all metadata
 *
 * Build outputs:
 *   src/static/session-pop.js      — Client-side PoP library
 *   src/static/session-pop.js.map  — Source map (served conditionally)
 *   src/static/pop-sw.js           — Service Worker
 *   src/static/pop-sw.js.map       — Source map
 *   src/static/terminal-init.js    — Terminal wrapper init
 *   src/static/terminal-init.js.map — Source map
 *   pop-client-manifest.ts         — SRI hashes, ETags, sizes
 */

import * as esbuild from 'esbuild';
import * as path from 'path';
import * as fs from 'fs';
import * as crypto from 'crypto';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const clientDir = path.join(__dirname, 'src', 'auth', 'client');
const staticDir = path.join(__dirname, 'src', 'static');

// ── Step 1: Type check ──────────────────────────────────────────────────────

function typeCheck() {
  const tsconfig = path.join(clientDir, 'tsconfig.json');
  try {
    execFileSync('npx', ['tsc', '--noEmit', '-p', tsconfig], {
      cwd: __dirname,
      stdio: 'pipe',
      encoding: 'utf8',
    });
  } catch (err) {
    // tsc writes diagnostics to stdout on failure
    const output = err.stdout || err.stderr || '';
    console.error('  Type check FAILED:\n' + output);
    throw new Error('Client TypeScript type check failed — fix errors above');
  }
}

// ── Step 2: Build bundles ────────────────────────────────────────────────────

/**
 * @typedef {{ file: string, js: string, map: string | null, size: number }} BuildResult
 */

/**
 * Build a single client entry point to a self-contained browser bundle.
 * @returns {Promise<BuildResult>}
 */
async function buildClientEntry(entryFile, outputFile, options = {}) {
  const entryPath = path.join(clientDir, entryFile);

  if (!fs.existsSync(entryPath)) {
    throw new Error(`Client source not found: ${entryPath}`);
  }

  const outputPath = path.join(staticDir, outputFile);

  const result = await esbuild.build({
    entryPoints: [entryPath],
    bundle: true,
    platform: 'browser',
    target: 'es2022',
    format: 'iife',
    minify: true,
    outfile: outputPath,
    sourcemap: 'linked',
    treeShaking: true,
    // Runtime dynamic imports served by the auth server — not resolvable at build time
    external: ['/_auth/static/pqc-mlkem.js'],
    legalComments: 'none',
    metafile: true,
    ...options,
  });

  // Read written files
  const js = fs.readFileSync(outputPath, 'utf8');
  const mapPath = outputPath + '.map';
  const map = fs.existsSync(mapPath) ? fs.readFileSync(mapPath, 'utf8') : null;

  // Verify the bundle is non-trivial (catch silent build failures)
  if (js.length < 100) {
    throw new Error(`Bundle suspiciously small (${js.length} bytes) for ${entryFile} — possible build failure`);
  }

  return { file: outputFile, js, map, size: js.length };
}

// ── Step 3: Integrity & ETag computation ─────────────────────────────────────

/**
 * Compute SRI integrity hash (SHA-384, base64-encoded).
 * @param {string} content
 * @returns {string}
 */
function computeSri(content) {
  const hash = crypto.createHash('sha384').update(content, 'utf8').digest('base64');
  return `sha384-${hash}`;
}

/**
 * Compute a short content-addressable ETag from SHA-256.
 * @param {string} content
 * @returns {string}
 */
function computeEtag(content) {
  const hash = crypto.createHash('sha256').update(content, 'utf8').digest('hex');
  return `"${hash.slice(0, 16)}"`;
}

// ── Step 4: Manifest generation ──────────────────────────────────────────────

/**
 * Generate pop-client-manifest.ts with build metadata.
 * This file is imported by the server to set SRI, ETag, and source map headers.
 */
function writeManifest(entries) {
  const lines = [
    '// AUTO-GENERATED by pop-client-bundle.build.mjs — do not edit.',
    '// Regenerate: pnpm --filter @ellul.ai/vps build',
    '',
    'export interface PopClientAsset {',
    '  /** SRI integrity hash (sha384) for <script integrity="..."> and CSP */',
    '  sri: string;',
    '  /** Content-addressable ETag for HTTP caching */',
    '  etag: string;',
    '  /** Bundle size in bytes */',
    '  size: number;',
    '  /** Whether a source map is available */',
    '  hasSourceMap: boolean;',
    '}',
    '',
    'export interface PopClientManifest {',
    '  [filename: string]: PopClientAsset;',
    '}',
    '',
    'export const POP_CLIENT_MANIFEST: PopClientManifest = {',
  ];

  for (const entry of entries) {
    lines.push(`  ${JSON.stringify(entry.file)}: {`);
    lines.push(`    sri: ${JSON.stringify(entry.sri)},`);
    lines.push(`    etag: ${JSON.stringify(entry.etag)},`);
    lines.push(`    size: ${entry.size},`);
    lines.push(`    hasSourceMap: ${entry.hasSourceMap},`);
    lines.push('  },');
  }

  lines.push('};');
  lines.push('');

  const manifestPath = path.join(__dirname, 'pop-client-manifest.ts');
  fs.writeFileSync(manifestPath, lines.join('\n'), 'utf8');
}

// ── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  // Step 1: Type check all client TypeScript
  console.log('  PoP client: type checking...');
  typeCheck();
  console.log('  PoP client: types OK');

  // Ensure static output directory exists
  fs.mkdirSync(staticDir, { recursive: true });

  // Step 2: Build all bundles in parallel
  const results = await Promise.all([
    buildClientEntry('session-pop.ts', 'session-pop.js'),
    buildClientEntry('pop-sw.ts', 'pop-sw.js'),
    buildClientEntry('terminal-init.ts', 'terminal-init.js'),
  ]);

  // Step 3: Compute integrity and ETags
  const manifest = results.map(({ file, js, map, size }) => ({
    file,
    sri: computeSri(js),
    etag: computeEtag(js),
    size,
    hasSourceMap: map !== null,
  }));

  // Step 4: Write manifest
  writeManifest(manifest);

  for (const entry of manifest) {
    console.log(`  PoP client: ${entry.file} (${(entry.size / 1024).toFixed(1)} KB) ${entry.sri.slice(0, 20)}...`);
  }
}

main().catch((err) => {
  console.error('Failed to build PoP client bundles:', err);
  process.exit(1);
});
